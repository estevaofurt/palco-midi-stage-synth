const hp={fft,solidWire,makeDesign,stringMode,spatialWeight,plateDesign,plateModes,patchWeight,ribDesign,generalizedEigen,mindlinModes,PolarizedBridge,PolarizedHammer,BoardCoupledBridge,radiationGrid,surfaceShape,radiationKernel,ResistiveBoard,relaxMemory};
import {renderModelDRegister} from './f10-model-d-register.mjs';
import {renderDLocal} from './f10c-d-local.mjs';
import {renderD4Board,BOARD_VARIANT} from './f10d-d4-board.mjs';
import {PILOT_NOTES} from './f10-pilot-geometry.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;},rejects=f=>{try{f();return false}catch{return true}};
const exact=(a,b)=>a.channels.every((c,j)=>c.length===b.channels[j].length&&c.every((v,i)=>Object.is(v,b.channels[j][i])));
const opts={midiVelocity:76,seconds:.025};
const cases=PILOT_NOTES.map(midi=>renderD4Board(hp,{...opts,midi}));
const g4=renderDLocal(hp,{...opts,midi:67,variant:'local8'});
check('G4 exact F10c pressure',exact(g4,cases[2]));
check('G4 exact F10c state',JSON.stringify(g4.checkpoint.state)===JSON.stringify(cases[2].checkpoint.state));
check('same board coefficient set across notes',cases.every(q=>JSON.stringify(q.meta.boardSignature)===JSON.stringify(cases[0].meta.boardSignature)));
check('all 337 mode coefficients captured',cases.every(q=>q.meta.boardSignature.length===337&&q.meta.boardSignature.every(([f,d])=>f>0&&d>0)));
check('all passive',cases.every(q=>q.meta.maxBalance<1e-9&&q.meta.maxIncrease<1e-9&&q.meta.attack.reboundMps<0));
check('fixed D4 variant',cases.every(q=>q.meta.boardVariant===BOARD_VARIANT&&q.meta.local.modifiedCount===4&&q.meta.local.factor===8&&q.meta.multiplier===3));
check('felt and string loss unchanged',cases.every(q=>q.meta.feltFactor===1.5&&q.meta.lossCase==='both-half'));
for(const [i,midi] of PILOT_NOTES.entries()){
 const original=renderModelDRegister(hp,{...opts,midi});
 check('wire exact '+midi,JSON.stringify(original.meta.centralWire)===JSON.stringify(cases[i].meta.centralWire));
 check('candidate changed pressure '+midi,!exact(original,cases[i]));
}
check('note mismatch',rejects(()=>renderD4Board(hp,{...opts,midi:60,prior:cases[0].checkpoint})));
check('original D checkpoint rejected',rejects(()=>renderD4Board(hp,{...opts,midi:67,prior:g4.checkpoint})));
check('invalid note',rejects(()=>renderD4Board(hp,{...opts,midi:21})));
check('velocity mismatch',rejects(()=>renderD4Board(hp,{...opts,midi:55,midiVelocity:127,prior:cases[0].checkpoint})));
const next=renderD4Board(hp,{...opts,midi:55,prior:cases[0].checkpoint});
check('continuous passive decay',next.checkpoint.elapsed===.05&&next.meta.attack===null&&next.meta.maxBalance<1e-9);
console.log('F10D_D4_TESTS '+n);
