import {hammerSpeed} from './f9-midi-velocity.mjs';
import {renderMidiStrike} from './f9-midi-strike.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;};const rejects=f=>{try{f();return false}catch{return true;}};
const selected=[1,4,8,12,16,20,24,36,52,76,100,127],cases=selected.map(midiVelocity=>renderMidiStrike(hp,{seconds:.1,midiVelocity}));
const rms=q=>Math.sqrt(q.channels.reduce((s,c)=>s+c.reduce((a,x)=>a+x*x,0),0)/q.channels.reduce((s,c)=>s+c.length,0));
check('mechanical mapping',cases.every((q,i)=>q.meta.velocity===hammerSpeed(selected[i])&&q.meta.midiVelocity===selected[i]&&q.meta.feltFactor===1.5));
check('passive and detached',cases.every(q=>q.meta.maxBalance<1e-9&&q.meta.maxIncrease<1e-9&&q.meta.attack.reboundMps<0));
check('sampled pressure progression',cases.every((q,i)=>i===0||rms(q)>rms(cases[i-1])));
check('sampled peak force progression',cases.every((q,i)=>i===0||q.meta.peakForce>cases[i-1].meta.peakForce));
const base=renderFeltSensitivity(hp,{seconds:.1,velocity:1,feltFactor:1.5}),medium=cases[selected.indexOf(76)];
check('medium bit exact',base.channels.every((c,j)=>c.length===medium.channels[j].length&&c.every((x,i)=>x===medium.channels[j][i])));
const quiet=renderFeltSensitivity(hp,{seconds:.1,velocity:.06,feltFactor:1.5});
check('quiet bit exact',quiet.channels.every((c,j)=>c.length===cases[0].channels[j].length&&c.every((x,i)=>x===cases[0].channels[j][i])));
check('zero is not struck',rejects(()=>renderMidiStrike(hp,{midiVelocity:0,seconds:.1})));
check('checkpoint guard',rejects(()=>renderMidiStrike(hp,{midiVelocity:4,seconds:.1,prior:cases[0].checkpoint})));
const next=renderMidiStrike(hp,{midiVelocity:1,seconds:.1,prior:cases[0].checkpoint});
check('continuation',next.checkpoint.elapsed===.2&&next.meta.attack===null&&next.meta.maxBalance<1e-9);
console.log('F9.18 MIDI strike tests passed:',n);
console.log('F918_SMOKE '+JSON.stringify(cases.map(q=>({midiVelocity:q.meta.midiVelocity,velocity:q.meta.velocity,rmsPa:rms(q),peakForce:q.meta.peakForce,attack:q.meta.attack,maxBalance:q.meta.maxBalance}))));
