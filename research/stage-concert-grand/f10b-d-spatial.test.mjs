const hp={fft,solidWire,makeDesign,stringMode,spatialWeight,plateDesign,plateModes,patchWeight,ribDesign,generalizedEigen,mindlinModes,PolarizedBridge,PolarizedHammer,BoardCoupledBridge,radiationGrid,surfaceShape,radiationKernel,ResistiveBoard,relaxMemory};
import {renderModelDRegister} from './f10-model-d-register.mjs';
import {renderDSpatial,patchFor,PATCHES} from './f10b-d-spatial.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;},rejects=f=>{try{f();return false}catch{return true}};
const opts={midi:67,midiVelocity:76,seconds:.025},original=renderModelDRegister(hp,opts);
const variants=Object.keys(PATCHES),cases=variants.map(variant=>renderDSpatial(hp,{...opts,variant}));
check('reference exact pressure',original.channels.every((c,j)=>c.length===cases[0].channels[j].length&&c.every((v,i)=>Object.is(v,cases[0].channels[j][i]))));
check('reference exact state',JSON.stringify(original.checkpoint.state)===JSON.stringify(cases[0].checkpoint.state));
check('variants change response',cases.slice(1).every(q=>q.channels[0].some((v,i)=>v!==original.channels[0][i])));
check('all passive',cases.every(q=>q.meta.maxBalance<1e-9&&q.meta.maxIncrease<1e-9&&q.meta.attack.reboundMps<0));
check('D damping preserved',cases.every(q=>q.meta.multiplier===3&&q.meta.selection.suspectMultiplier===4&&q.meta.feltFactor===1.5&&q.meta.lossCase==='both-half'));
check('same wire',cases.every(q=>JSON.stringify(q.meta.centralWire)===JSON.stringify(original.meta.centralWire)));
check('same modes',cases.every(q=>JSON.stringify(q.meta.spatial.modes.map(m=>m.frequencyHz))===JSON.stringify(cases[0].meta.spatial.modes.map(m=>m.frequencyHz))));
check('finite weights',cases.every(q=>q.meta.spatial.modes.length>0&&q.meta.spatial.modes.every(m=>Number.isFinite(m.weight))));
check('coordinates',cases.every((q,i)=>q.meta.spatial.patch.xM===.83+PATCHES[variants[i]]&&q.meta.spatial.patch.yM===.46));
check('checkpoint scope',rejects(()=>renderDSpatial(hp,{...opts,variant:'plus8cm',prior:cases[1].checkpoint})));
check('note scope',rejects(()=>renderDSpatial(hp,{...opts,midi:60})));
check('invalid variant',rejects(()=>patchFor({xM:.83,yM:.46,dxM:.04,dyM:.025},'invalid')));
const next=renderDSpatial(hp,{...opts,variant:'minus8cm',prior:cases[1].checkpoint});
check('continued decay',next.checkpoint.elapsed===.05&&next.meta.attack===null&&next.meta.maxBalance<1e-9);
console.log('F10B_D_SPATIAL_TESTS '+n);
console.log('F10B_D_SPATIAL_MODES '+JSON.stringify(cases.map(q=>q.meta.spatial)));
