const next=renderFeltSensitivity(hp,{...opts,feltFactor:.75,prior:cases[0].checkpoint});
check('continuous free decay',next.checkpoint.elapsed===.05&&next.meta.attack===null&&next.meta.peakForce===0&&next.meta.maxBalance<1e-9&&next.meta.hammerImpulseNs===cases[0].meta.hammerImpulseNs);
