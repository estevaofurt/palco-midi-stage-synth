let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;};const rejects=f=>{try{f();return false}catch{return true;}};
const opts={seconds:.025,boardFactor:.5,angleRad:.5,spreadCents:.5,lossCase:'both-half'};
const base=renderStringLoss(hp,opts),cases=FELT_FACTORS.map(feltFactor=>renderFeltSensitivity(hp,{...opts,feltFactor})),control=cases[1];
const rel=(a,b)=>{let d=0,s=0;for(let j=0;j<a.length;j++){if(a[j].length!==b[j].length)throw Error('length');for(let i=0;i<a[j].length;i++){d+=(a[j][i]-b[j][i])**2;s+=a[j][i]**2;}}return Math.sqrt(d/s);};
