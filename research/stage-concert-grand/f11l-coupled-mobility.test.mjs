import {solveComplex,boardMobility,contactDrive,coupledMobility,scanBand} from './f11l-coupled-mobility.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++};
const near=(a,b,t=1e-10)=>Math.abs(a-b)<=t;
const x=solveComplex([[[0,0],[2,0]],[[1,1],[0,0]]],[[4,2],[2,0]]);
check('pivot complex',near(x[0][0],1)&&near(x[0][1],-1)&&near(x[1][0],2)&&near(x[1][1],1));
const f=100,w=2*Math.PI*f,board={modes:[{lambda:w*w,w:2,frequencyHz:f,coeff:{dampingNsM:3}}],blocks:[{indices:[0],R:[[1]]}]};
const y=boardMobility(board,f);
check('single oscillator resonance',near(y.Y[0],1)&&near(y.Y[1],0));
check('modal velocity',near(y.vel[0][0],.5)&&near(y.vel[0][1],0));
const bridge={wires:[{},{}],vAxis:{modes:[]},mobility:()=>({vv:[.5,0]})};
const joint={c:2,k:0},q=coupledMobility(bridge,board,joint,f);
check('condensed contact',near(contactDrive(bridge,f)[0],.26));
check('series coupling',near(q.input[0],.375)&&near(q.contactBoardVelocity,.065));
check('modal norm',near(q.modalVelocityNorm,.0325));
const free=coupledMobility(bridge,board,{c:0,k:0},f);
check('disconnected',near(free.input[0],.5)&&free.modalVelocityNorm===0);
const scan=scanBand(bridge,board,joint,f,100,.05);
check('scan peaks',scan.peaks.length>0&&Math.abs(scan.peaks[0].f-f)<.05);
console.log('F11L_MOBILITY_TESTS '+n);
