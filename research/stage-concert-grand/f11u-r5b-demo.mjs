const [out='r5b',variant='K750',mode='pedal',factorArg='1']=process.argv.slice(2);
if(!['pedal','dry','held'].includes(mode))throw RangeError('program');
const id=mode==='held'?'C4-held-mf':'original-phrase-'+mode;
const seconds=mode==='held'?12:10;
const notes=mode==='held'?[60]:phraseNotes;
const events=mode==='held'?[{ms:0,type:'on',midi:60,velocity:76},{ms:10000,type:'off',midi:60}]:phrase().filter(e=>mode==='pedal'||e.type!=='pedal');
const q=renderResonanceTrial(hp,{notes,events,variant,seconds,releaseRate:25,distance:.3,lossFactor:Number(factorArg)});
// Fixed shared listening headroom across all candidates, not per-chord normalization.
const gain=S50_REFERENCE.gain*.20;
const y=q.channels.map(x=>{let N=1;while(N<x.length)N*=2;const re=new Float64Array(N),im=new Float64Array(N);re.set(x);hp.fft(re,im);for(let i=0;i<N;i++){const f=Math.min(i,N-i)*48000/N,w=f<=8000?1:f>=12000?0:.5*(1+Math.cos(Math.PI*(f-8000)/4000));re[i]*=w;im[i]*=w;}hp.fft(re,im,true);return re.slice(0,x.length);});
const hi=wave24(y,48000,gain),lo=waveBytes(y,48000,gain),pair=inspectPair(lo.bytes,hi.bytes);
if(hi.clipped||lo.clipped||hi.peak>.85||pair.frames!==Math.round(seconds*48000)+q.meta.maxDelay)throw Error('chord export gate');
const rms=(a,b)=>{let s=0,n=0;for(const ch of y)for(let i=Math.round(a*48000);i<Math.round(b*48000);i++){s+=(ch[i]*gain)**2;n++;}return 10*Math.log10(Math.max(s/n,1e-30));};
const metrics=mode==='held'?{attack:rms(0,.05),held1:rms(1,1.5),held3:rms(3,3.5),held5:rms(5,5.5),held8:rms(8,8.5),held9:rms(9,9.5),release:rms(10.3,10.5),tail:rms(11,11.5)}:{attack:rms(0,.05),initial:rms(0,.5),arpeggio:rms(1,1.5),chord:rms(3.5,3.6),held:rms(4.2,4.4),pedalTail:rms(5.1,5.3),afterPedal:rms(5.6,5.8),end:rms(9,9.5)};
const sha=createHash('sha256').update(hi.bytes).digest('hex'),result={...q.meta,metrics,caseId:id,gain,peak:hi.peak,clipped:hi.clipped,pair,sha256:sha,scope:'continuous shared board, staggered/repeated hammer strikes and R2 two-axis release; fixed .20 S50 gain; fixed .3m height, selective board loss'};
mkdirSync(out,{recursive:true});const stem=out+'/'+id+'_'+variant+'_L'+factorArg+'_pure-base';
writeFileSync(stem+'_24bit.wav',hi.bytes,{flag:'wx'});writeFileSync(stem+'.wav',lo.bytes,{flag:'wx'});writeFileSync(stem+'.json',JSON.stringify(result,null,2),{flag:'wx'});
