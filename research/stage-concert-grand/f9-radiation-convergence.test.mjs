import {modalBoardResponse,complexSurface,pressureResponse,responseDifference} from './f9-radiation-convergence.mjs';
import {boardMobility} from './f9-loaded-mobility.mjs';
import {radiationGrid,surfaceShape,harmonicRadiation,radiationKernel,kernelResponse} from './surface-radiation.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;};
const board={modes:[{lambda:400,w:2,coeff:{dampingNsM:3}}],blocks:[{indices:[0],R:[[4]]}]},f=10,q=modalBoardResponse(board,f),old=boardMobility(board,f);
check('mobility parity',q.Y.every((x,i)=>x===old.Y[i])&&q.powerResidualW===old.powerResidualW);
check('passive balance',q.inputW>0&&Math.abs(q.powerResidualW)<1e-12&&q.maxRelativeResidual<1e-12);
const w=2*Math.PI*f,den=(400-w*w)**2+(7*w)**2;
check('analytic acceleration',Math.abs(q.acceleration[0][0]+2*w*w*(400-w*w)/den)<1e-12&&Math.abs(q.acceleration[0][1]-2*w*w*7*w/den)<1e-12);
const mode={components:[{m:1,n:1,kx:Math.PI,ky:Math.PI,coefficient:2}]},field=complexSurface([mode],[[1,0]]),grid=radiationGrid({lengthM:1,widthM:1},{x:.2,y:.3,z:1},{nx:12,ny:10});
const a=pressureResponse(grid,field,1000),b=harmonicRadiation(grid,(x,y)=>surfaceShape(mode,x,y),1000);
check('continuous quadrature parity',Math.hypot(a[0]-b.re,a[1]-b.im)<1e-12);
const k=kernelResponse(radiationKernel(grid,(x,y)=>surfaceShape(mode,x,y),48000),1000),v=pressureResponse(grid,field,1000,48000);
check('linear delay kernel parity',Math.hypot(v[0]-k.re,v[1]-k.im)<1e-12);
const summed=complexSurface([mode,mode],[[1,2],[3,4]])(.5,.5);
check('complex superposition',summed[0]===8&&summed[1]===12);
const d=responseDifference([1,0],[0,1]);check('phase sensitive',Math.abs(d.relativeComplexError-Math.SQRT2)<1e-12&&d.magnitudeDeltaDb===0);
check('null reference censored',responseDifference([0,0],[1,0]).relativeComplexError===null);
console.log('F9.16c radiation tests passed:',n);
