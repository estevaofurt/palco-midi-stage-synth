import {solidWire} from '../c3x-physical/c4-wire-consistency.mjs';
import {makeDesign} from './c4-design.mjs';
import {stringMode,spatialWeight} from './stiff-string.mjs';
import {plateDesign,plateModes,patchWeight} from './orthotropic-plate.mjs';
import {ribDesign,generalizedEigen} from './ribbed-plate.mjs';
import {mindlinModes} from './mindlin-plate.mjs';
import {PolarizedBridge,PolarizedHammer} from './polarized-bridge.mjs';
import {BoardCoupledBridge} from './board-coupling.mjs';
import {radiationGrid,surfaceShape,radiationKernel} from './surface-radiation.mjs';
import {ResistiveBoard} from './radiation-loading.mjs';
import {relaxMemory} from './felt-memory.mjs';
import {fft} from './f8-render.mjs';
const hp={fft,solidWire,makeDesign,stringMode,spatialWeight,plateDesign,plateModes,patchWeight,ribDesign,generalizedEigen,mindlinModes,PolarizedBridge,PolarizedHammer,BoardCoupledBridge,radiationGrid,surfaceShape,radiationKernel,ResistiveBoard,relaxMemory};

import {buildChord,renderHeldChord} from './f11s-held-chord-render.mjs';
import {renderBassSupportTrial} from './f11q-bass-support-trial.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++},rejects=f=>{try{f();return false}catch{return true}};
const opts={notes:[48],midiVelocity:76,variant:'K750',seconds:.05};
const a=renderHeldChord(hp,opts),b=renderBassSupportTrial(hp,{midi:48,midiVelocity:76,variant:'K750',seconds:.05});
check('337 modes',a.meta.modeCount===337);
check('identical damping signature',JSON.stringify(a.meta.boardSignature)===JSON.stringify(b.meta.boardSignature));
check('one note parity',a.channels.every((c,j)=>c.length===b.channels[j].length&&c.every((v,i)=>Math.abs(v-b.channels[j][i])<1e-8)));
const q=renderHeldChord(hp,{notes:[48,64,67,72],variant:'K750',seconds:.05,midiVelocity:76});
check('four strikes',q.meta.peaks.length===4&&q.meta.peaks.every(x=>x>0)&&q.meta.rebound.every(x=>x<0));
check('shared board passive',q.meta.sharedBoard&&q.meta.maxBalance<1e-9&&q.meta.maxIncrease<1e-9&&q.meta.contactResidual<1e-8);
check('stereo response',q.channels.length===2&&q.channels.every(c=>c.length===2400+239&&c.every(Number.isFinite)&&c.some(x=>x!==0))&&q.channels[0].some((x,i)=>x!==q.channels[1][i]));
check('board signature',JSON.stringify(q.meta.boardSignature)===JSON.stringify(a.meta.boardSignature));
check('reject duplicate notes',rejects(()=>buildChord(hp,{notes:[48,48]})));
check('reject unavailable notes',rejects(()=>buildChord(hp,{notes:[21]})));
console.log('F11S_CHORD_TESTS '+n);
console.log('F11S_CHORD_SMOKE '+JSON.stringify({maxBalance:q.meta.maxBalance,maxIncrease:q.meta.maxIncrease,contactResidual:q.meta.contactResidual,peaks:q.meta.peaks,rebound:q.meta.rebound}));
