let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;},rejects=f=>{try{f();return false}catch{return true}};
const opts={midi:60,midiVelocity:76,seconds:.025},a=renderD4Board(hp,opts),ref=renderD4Sustain(hp,{...opts,factor:1}),d=renderD4Sustain(hp,opts);
const exact=(x,y)=>x.channels.every((c,j)=>c.length===y.channels[j].length&&c.every((v,i)=>Object.is(v,y.channels[j][i])));
