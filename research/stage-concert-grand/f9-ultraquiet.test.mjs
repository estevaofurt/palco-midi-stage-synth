const hp={fft,solidWire,makeDesign,stringMode,spatialWeight,plateDesign,plateModes,patchWeight,ribDesign,generalizedEigen,mindlinModes,PolarizedBridge,PolarizedHammer,BoardCoupledBridge,radiationGrid,surfaceShape,radiationKernel,ResistiveBoard,relaxMemory};
import {renderFeltSensitivity} from './f9-felt-sensitivity.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;};
const speeds=[.06,.09,.12,.15],cases=speeds.map(velocity=>renderFeltSensitivity(hp,{seconds:.1,velocity,feltFactor:1.5}));
const rms=q=>Math.sqrt(q.channels.reduce((s,c)=>s+c.reduce((a,x)=>a+x*x,0),0)/q.channels.reduce((s,c)=>s+c.length,0));
check('all passive and detached',cases.every(q=>q.meta.maxBalance<1e-9&&q.meta.maxIncrease<1e-9&&q.meta.attack.reboundMps<0&&q.meta.attack.contactSpanS>0));
check('same felt and loss',cases.every(q=>q.meta.feltFactor===1.5&&q.meta.lossCase==='both-half'));
check('peak force grows with velocity',cases.every((q,i)=>i===0||q.meta.peakForce>cases[i-1].meta.peakForce));
check('initial RMS grows with velocity',cases.every((q,i)=>i===0||rms(q)>rms(cases[i-1])));
check('impulse balance',cases.every((q,i)=>Math.abs(q.meta.attack.impulseNs-.01*(speeds[i]-q.meta.attack.reboundMps))<1e-12));
const next=renderFeltSensitivity(hp,{seconds:.1,velocity:.06,feltFactor:1.5,prior:cases[0].checkpoint});
check('quiet checkpoint continuation',next.checkpoint.elapsed===.2&&next.meta.attack===null&&next.meta.maxBalance<1e-9);
console.log('F9.17c very quiet dynamics tests passed:',n);
console.log('F917C_SMOKE '+JSON.stringify(cases.map((q,i)=>({velocity:speeds[i],pressureRms:rms(q),attack:q.meta.attack,peakPa:q.meta.peakPa,maxBalance:q.meta.maxBalance,maxIncrease:q.meta.maxIncrease}))));
