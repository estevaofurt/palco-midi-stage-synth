let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;},rejects=f=>{try{f();return false}catch{return true}};
const opts={midi:67,midiVelocity:76,seconds:.025},original=renderModelDRegister(hp,opts);
const variants=Object.keys(FACTORS),cases=variants.map(variant=>renderDLocal(hp,{...opts,variant}));
check('reference exact pressure',original.channels.every((c,j)=>c.length===cases[0].channels[j].length&&c.every((v,i)=>Object.is(v,cases[0].channels[j][i]))));
check('reference exact state',JSON.stringify(original.checkpoint.state)===JSON.stringify(cases[0].checkpoint.state));
check('variants change response',cases.slice(1).every(q=>q.channels[0].some((v,i)=>v!==original.channels[0][i])));
check('all passive',cases.every(q=>q.meta.maxBalance<1e-9&&q.meta.maxIncrease<1e-9&&q.meta.attack.reboundMps<0));
check('D global configuration',cases.every(q=>q.meta.multiplier===3&&q.meta.feltFactor===1.5&&q.meta.lossCase==='both-half'));
check('same wire',cases.every(q=>JSON.stringify(q.meta.centralWire)===JSON.stringify(original.meta.centralWire)));
check('same target modes',cases.every(q=>q.meta.local.modes.length===4&&q.meta.local.modes.every((m,i)=>Math.abs(m.frequencyHz-TARGETS[i])<.001)));
check('four local changes',cases.every((q,i)=>q.meta.local.modifiedCount===(i?4:0)&&q.meta.local.modeCount===337));
check('absolute factors',cases.slice(1).every(q=>q.meta.local.modes.every(m=>Math.abs(m.after-q.meta.local.factor*2*(1+.00025*2*Math.PI*m.frequencyHz))<1e-10)));
check('unchanged reference loss',cases[0].meta.local.modes.every(m=>m.before===m.after));
check('positive compliance',cases.every(q=>q.meta.local.compliance>0));
check('checkpoint scope',rejects(()=>renderDLocal(hp,{...opts,variant:'local8',prior:cases[1].checkpoint})));
check('note scope',rejects(()=>renderDLocal(hp,{...opts,midi:60})));
check('invalid variant',rejects(()=>renderDLocal(hp,{...opts,variant:'invalid'})));
const next=renderDLocal(hp,{...opts,variant:'local6',prior:cases[1].checkpoint});
check('continued decay',next.checkpoint.elapsed===.05&&next.meta.attack===null&&next.meta.maxBalance<1e-9);
