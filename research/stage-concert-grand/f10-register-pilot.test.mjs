const hp={fft,solidWire,makeDesign,stringMode,spatialWeight,plateDesign,plateModes,patchWeight,ribDesign,generalizedEigen,mindlinModes,PolarizedBridge,PolarizedHammer,BoardCoupledBridge,radiationGrid,surfaceShape,radiationKernel,ResistiveBoard,relaxMemory};
import {renderFeltSensitivity} from './f9-felt-sensitivity.mjs';
import {pilotGeometry,pilotWire,PILOT_NOTES} from './f10-pilot-geometry.mjs';
import {renderRegisterPilot} from './f10-register-pilot.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;};const rejects=f=>{try{f();return false}catch{return true;}};
const wires=PILOT_NOTES.map(m=>pilotWire(hp,m)),g=PILOT_NOTES.map(pilotGeometry);
check('length ordering',g[0].lengthM>g[1].lengthM&&g[1].lengthM>g[2].lengthM);
check('fundamental targets',wires.every((w,i)=>Math.abs(stringMode(w,1).frequencyHz-g[i].f1Hz)<1e-9));
check('physical inharmonicity increases',wires[0].B<wires[1].B&&wires[1].B<wires[2].B);
check('geometry remains steel and positive tension',wires.every(w=>w.diameterM===.00096&&w.tensionN>0&&w.youngPa===200e9));
check('three unison targets',PILOT_NOTES.every(m=>[-.5,0,.5].every(c=>Math.abs(pilotWire(hp,m,c).f1Hz/(pilotGeometry(m).f1Hz*2**(c/1200))-1)<1e-12)));
check('invalid note rejected',rejects(()=>pilotGeometry(21)));
const opts={seconds:.025,velocity:1},base=renderFeltSensitivity(hp,{...opts,feltFactor:1.5}),cases=PILOT_NOTES.map(midi=>renderRegisterPilot(hp,{...opts,midi}));
check('C4 exact pressure',base.channels.every((c,j)=>c.length===cases[1].channels[j].length&&c.every((v,i)=>v===cases[1].channels[j][i])));
check('C4 exact energy',base.meta.finalEnergyJ===cases[1].meta.finalEnergyJ);
check('all passive and detached',cases.every(q=>q.meta.maxBalance<1e-9&&q.meta.maxIncrease<1e-9&&q.meta.attack.reboundMps<0));
check('changed note changes response',cases.filter((_,i)=>i!==1).every(q=>q.channels[0].some((x,i)=>x!==base.channels[0][i])));
check('note checkpoint guarded',rejects(()=>renderRegisterPilot(hp,{...opts,midi:67,prior:cases[0].checkpoint})));
const next=renderRegisterPilot(hp,{...opts,midi:55,prior:cases[0].checkpoint});
check('continuous decay',next.checkpoint.elapsed===.05&&next.meta.attack===null&&next.meta.maxBalance<1e-9);
console.log('F10 pilot tests passed:',n);
console.log('F10_PILOT_SMOKE '+JSON.stringify({cases:cases.map(q=>q.meta),next:next.meta}));
