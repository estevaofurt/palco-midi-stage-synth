import {renderD4Sustain} from './f10f-d4-sustain.mjs';
import {renderD4LossPilot,trialLoss} from './f10g-d4-loss-pilot.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;},rejects=f=>{try{f();return false}catch{return true}};
const opts={midiVelocity:76,seconds:.025};
const exact=(x,y)=>x.channels.every((c,j)=>c.length===y.channels[j].length&&c.every((v,i)=>Object.is(v,y.channels[j][i])));
const cases=EXTENDED_NOTES.map(midi=>renderD4LossPilot(hp,{...opts,midi,factor:.5}));
check('all passive',cases.every(q=>q.meta.maxBalance<1e-9&&q.meta.maxIncrease<1e-9&&q.meta.attack.reboundMps<0));
check('common board',cases.every(q=>q.meta.boardSignature.length===337&&JSON.stringify(q.meta.boardSignature)===JSON.stringify(cases[0].meta.boardSignature)));
check('common loss',cases.every(q=>JSON.stringify(q.meta.actualStringLoss)===JSON.stringify({verticalLoss:[.1,.0002],horizontalLoss:[.05,.00012]})));
for(const midi of [60,67]){
 const a=renderD4Sustain(hp,{...opts,midi,factor:.5}),d=cases[EXTENDED_NOTES.indexOf(midi)];
 check('exact S50 pressure '+midi,exact(a,d));
 check('exact S50 state '+midi,JSON.stringify(a.checkpoint.state)===JSON.stringify(d.checkpoint.state));
}
const original=renderExtendedD4(hp,{...opts,midi:57}),ref=renderD4LossPilot(hp,{...opts,midi:57,factor:1});
check('exact D4 A3 control',exact(original,ref)&&JSON.stringify(original.checkpoint.state)===JSON.stringify(ref.checkpoint.state));
const s25=renderD4LossPilot(hp,{...opts,midi:60,factor:.25});
check('S25 coefficients',JSON.stringify(s25.meta.actualStringLoss)===JSON.stringify({verticalLoss:[.05,.0002],horizontalLoss:[.025,.00012]}));
check('S25 passive',s25.meta.maxBalance<1e-9&&s25.meta.maxIncrease<1e-9);
check('S25 changed pressure',!exact(s25,cases[EXTENDED_NOTES.indexOf(60)]));
check('S25 same board',JSON.stringify(s25.meta.boardSignature)===JSON.stringify(cases[0].meta.boardSignature));
check('factor guard',rejects(()=>renderD4LossPilot(hp,{...opts,midi:60,factor:.5,prior:s25.checkpoint})));
check('invalid factor',rejects(()=>trialLoss({verticalLoss:[.2,.0002],horizontalLoss:[.1,.00012]},0)));
check('note guard',rejects(()=>renderD4LossPilot(hp,{...opts,midi:67,factor:.25,prior:s25.checkpoint})));
const next=renderD4LossPilot(hp,{...opts,midi:60,factor:.25,prior:s25.checkpoint});
check('continuity',next.checkpoint.elapsed===.05&&next.meta.attack===null&&next.meta.maxBalance<1e-9);
console.log('F10G_LOSS_TESTS '+n);
