check('note checkpoint guarded',rejects(()=>renderModelDRegister(hp,{...opts,midi:67,prior:cases[0].checkpoint})));
const next=renderModelDRegister(hp,{...opts,midi:55,prior:cases[0].checkpoint});
check('continuous decay',next.checkpoint.elapsed===.05&&next.meta.attack===null&&next.meta.maxBalance<1e-9);
check('locked D configuration',MODEL_D.multiplier===3&&MODEL_D.suspectMultiplier===4&&MODEL_D.feltFactor===1.5&&MODEL_D.gain===.36767023440034063);
check('D board scope',cases.every(q=>q.meta.multiplier===3&&q.meta.selection.globalMultiplier===3&&q.meta.selection.suspectMultiplier===4&&q.meta.selection.modifiedCount===5&&q.meta.selection.modeCount===337&&q.meta.feltFactor===1.5&&q.meta.lossCase==='both-half'));
check('D checkpoint velocity guarded',rejects(()=>renderModelDRegister(hp,{...opts,midi:55,midiVelocity:127,prior:cases[0].checkpoint})));
