let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;};const rejects=f=>{try{f();return false}catch{return true;}};
const wires=PILOT_NOTES.map(m=>pilotWire(hp,m)),g=PILOT_NOTES.map(pilotGeometry);
check('length ordering',g[0].lengthM>g[1].lengthM&&g[1].lengthM>g[2].lengthM);
check('fundamental targets',wires.every((w,i)=>Math.abs(stringMode(w,1).frequencyHz-g[i].f1Hz)<1e-9));
check('physical inharmonicity increases',wires[0].B<wires[1].B&&wires[1].B<wires[2].B);
