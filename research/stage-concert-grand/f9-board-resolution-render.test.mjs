const rel=(a,b)=>{let d=0,s=0;for(let j=0;j<a.length;j++){if(a[j].length!==b[j].length)throw Error('length');for(let i=0;i<a[j].length;i++){d+=(a[j][i]-b[j][i])**2;s+=a[j][i]**2;}}return Math.sqrt(d/s);};
