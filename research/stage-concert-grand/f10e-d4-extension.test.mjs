import {renderExtendedD4,extendedGeometry,extendedWire,EXTENDED_NOTES} from './f10e-d4-extension.mjs';
import {PILOT_NOTES} from './f10-pilot-geometry.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++;},rejects=f=>{try{f();return false}catch{return true}};
const opts={midiVelocity:76,seconds:.025},cases=EXTENDED_NOTES.map(midi=>renderExtendedD4(hp,{...opts,midi})),wires=EXTENDED_NOTES.map(m=>extendedWire(hp,m));
check('length ordering',wires.every((w,i)=>i===0||w.lengthM<wires[i-1].lengthM));
check('positive tension',wires.every(w=>w.tensionN>0&&w.diameterM===.00096));
check('pitch targets',wires.every((w,i)=>Math.abs(stringMode(w,1).frequencyHz-extendedGeometry(EXTENDED_NOTES[i]).f1Hz)<1e-9));
check('unison targets',EXTENDED_NOTES.every(m=>[-.5,0,.5].every(c=>Math.abs(extendedWire(hp,m,c).f1Hz/(extendedGeometry(m).f1Hz*2**(c/1200))-1)<1e-12)));
check('passive all notes',cases.every(q=>q.meta.maxBalance<1e-9&&q.meta.maxIncrease<1e-9&&q.meta.attack.reboundMps<0));
check('same board all notes',cases.every(q=>q.meta.boardSignature.length===337&&JSON.stringify(q.meta.boardSignature)===JSON.stringify(cases[0].meta.boardSignature)));
check('same configuration',cases.every(q=>q.meta.multiplier===3&&q.meta.local.factor===8&&q.meta.feltFactor===1.5&&q.meta.lossCase==='both-half'));
for(const midi of PILOT_NOTES){
 const a=renderD4Board(hp,{...opts,midi}),d=cases[EXTENDED_NOTES.indexOf(midi)];
 check('exact old pressure '+midi,a.channels.every((c,j)=>c.length===d.channels[j].length&&c.every((v,i)=>Object.is(v,d.channels[j][i]))));
 check('exact old state '+midi,JSON.stringify(a.checkpoint.state)===JSON.stringify(d.checkpoint.state));
}
check('invalid note',rejects(()=>extendedGeometry(21)));
check('checkpoint note guard',rejects(()=>renderExtendedD4(hp,{...opts,midi:72,prior:cases[0].checkpoint})));
check('checkpoint variant guard',rejects(()=>renderExtendedD4(hp,{...opts,midi:53,prior:{...cases[0].checkpoint,boardVariant:'other'}})));
const next=renderExtendedD4(hp,{...opts,midi:53,prior:cases[0].checkpoint});
check('continued passive decay',next.checkpoint.elapsed===.05&&next.meta.attack===null&&next.meta.maxBalance<1e-9);
const oldNext=renderExtendedD4(hp,{...opts,midi:60,prior:cases[3].checkpoint});
check('old note continuation',oldNext.checkpoint.elapsed===.05&&oldNext.meta.attack===null&&oldNext.meta.maxBalance<1e-9);
console.log('F10E_EXTENSION_TESTS '+n);
