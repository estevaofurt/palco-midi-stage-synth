import {readFileSync} from 'node:fs';
import {auditScale} from './f11b-s50-scale-audit.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++},rejects=f=>{try{f();return false}catch{return true}};
const data=JSON.parse(readFileSync(new URL('../../audio/analysis_f10h_d4_ci.json',import.meta.url),'utf8'));
const a=auditScale(data.cases);
check('reference accepted',a.valid===21&&a.expected===60&&a.missing.length===39&&a.rejected.length===0);
check('reference dynamics',a.dynamics.length===7&&a.dynamics.every(x=>x.peakMonotonic&&x.attackMonotonic&&x.tailMonotonic));
check('no invented adjacency',a.pairs.length===0);
const source=data.cases.filter(x=>x.midi===60),next=source.map(x=>({...x,midi:61,rms:x.rms.map(w=>({...w,rms:w.rms*3}))}));
const b=auditScale([...source,...next],{notes:[60,61]});
check('complete matrix',b.valid===6&&!b.missing.length&&b.pairs.length===3);
check('jump flags',b.flagged.length===3&&b.flagged.every(x=>Math.abs(x.attackDb-20*Math.log10(3))<1e-12));
check('uniform decay unchanged',b.pairs.every(x=>Math.abs(x.decayDifferenceDb)<1e-12));
check('rejected explicit',auditScale([...source,{midi:61,midiVelocity:127,conclusion:'failure',reason:'clipping',peak:1.1,clipped:2}],{notes:[60,61]}).rejected.length===1);
check('duplicate rejected',rejects(()=>auditScale([...source,source[0]])));
check('gain guard',rejects(()=>auditScale([{...source[0],gain:1}])));
check('peak guard',rejects(()=>auditScale([{...source[0],peak:.86}])));
check('clipping guard',rejects(()=>auditScale([{...source[0],clipped:1}])));
check('nonfinite guard',rejects(()=>auditScale([{...source[0],maxBalance:NaN}])));
console.log('F11B_AUDIT_TESTS '+n);
