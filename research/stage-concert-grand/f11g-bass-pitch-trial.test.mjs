const hp={fft,solidWire,makeDesign,stringMode,spatialWeight,plateDesign,plateModes,patchWeight,ribDesign,generalizedEigen,mindlinModes,PolarizedBridge,PolarizedHammer,BoardCoupledBridge,radiationGrid,surfaceShape,radiationKernel,ResistiveBoard,relaxMemory};
import {renderBassPilot} from './f11d-bass-render.mjs';
import {renderBassPitchTrial,PITCH_VARIANTS} from './f11g-bass-pitch-trial.mjs';
let n=0;const check=(m,b)=>{if(!b)throw Error(m);n++},rejects=f=>{try{f();return false}catch{return true}};
const opts={midi:48,midiVelocity:76,seconds:.05};
const exact=(a,b)=>a.channels.every((c,j)=>c.length===b.channels[j].length&&c.every((v,i)=>Object.is(v,b.channels[j][i])));
const ref=renderBassPilot(hp,{...opts,count:2}),cases=Object.keys(PITCH_VARIANTS).map(variant=>renderBassPitchTrial(hp,{...opts,variant}));
check('A exact pressure',exact(ref,cases[0]));
check('A exact state',JSON.stringify(ref.checkpoint.state)===JSON.stringify(cases[0].checkpoint.state));
check('two wires only',cases.every(q=>q.meta.wires.length===2));
check('same board',cases.every(q=>JSON.stringify(q.meta.boardSignature)===JSON.stringify(ref.meta.boardSignature)));
check('same losses',cases.every(q=>JSON.stringify(q.meta.actualStringLoss)===JSON.stringify(ref.meta.actualStringLoss)));
check('same winding',cases.every(q=>q.meta.wires.every((w,i)=>w.linearDensityKgM===ref.meta.wires[i].linearDensityKgM&&w.EI===ref.meta.wires[i].EI)));
check('unison B D',cases[1].meta.wires[0].f1Hz===cases[1].meta.wires[1].f1Hz&&cases[3].meta.wires[0].f1Hz===cases[3].meta.wires[1].f1Hz);
check('spread C A',JSON.stringify(cases[2].meta.wires)===JSON.stringify(cases[0].meta.wires));
check('mass factor',cases.map(q=>q.meta.bridgeMassKg).join(',')==='0.025,0.025,0.05,0.05');
check('passive',cases.every(q=>q.meta.maxBalance<1e-9&&q.meta.maxIncrease<1e-9&&q.meta.reboundMps<0));
check('changed pressure',cases.slice(1).every(q=>!exact(q,cases[0])));
check('variant guard',rejects(()=>renderBassPitchTrial(hp,{...opts,variant:'B',prior:cases[0].checkpoint})));
check('unknown guard',rejects(()=>renderBassPitchTrial(hp,{...opts,variant:'X'})));
for(const variant of ['B','C','D']){
 const a=cases[Object.keys(PITCH_VARIANTS).indexOf(variant)],q=renderBassPitchTrial(hp,{...opts,variant,prior:a.checkpoint});
 check('continuity '+variant,q.checkpoint.elapsed===.1&&q.meta.maxBalance<1e-9&&q.meta.peakForce===0);
}
console.log('F11G_TRIAL_TESTS '+n);
