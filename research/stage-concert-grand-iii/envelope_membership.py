"""Exact membership in the upper prism plus hinged-lid wedge.
The union need not be convex. A common supporting-halfspace test can reject
points that are physically inside. Never use the convex hull as a substitute.
"""
import numpy as np
from board_contour import margins
from neumann_envelope import samples

def clearance(poly,height,angle,points):
    poly=np.asarray(poly,float);q=np.atleast_2d(np.asarray(points,float))
    if q.shape[1]!=3 or not np.isfinite(q).all() or height<=0 or not 0<angle<90:
        raise ValueError('invalid envelope geometry')
    a=np.deg2rad(angle);h=poly[:,0].min()
    z=q[:,2];dz=np.maximum(z-height,0.)
    # The wedge is generated by translation parallel to the displacement
    # vector of the hinged lid. Undo that translation at each height.
    xy=q[:,:2].copy()
    xy[:,0]+=(1-np.cos(a))/np.sin(a)*dz
    side=margins(poly,xy)
    # The roof plane is z=h_top+tan(a)*(x-x_hinge). Normalized signed
    # distances to roof and bottom; side is in the inverse planar chart.
    roof=(height-z)*np.cos(a)+(q[:,0]-h)*np.sin(a)
    return np.minimum(np.minimum(side,roof),z)

def internal_exact(poly,height,angle,surfaces,ports,inside,order,scale):
    if not 0<scale<1:raise ValueError('interior scale')
    x,_,_,_=samples(surfaces,ports,order);q=inside+scale*(x-inside)
    d=clearance(poly,height,angle,q);valid=d>1e-10
    # Retain the old halfspace check as a diagnostic, not as geometry truth.
    old=np.ones(len(q),bool)
    for s in surfaces:old&=(q-s['panel'].origin)@s['normal']<-1e-10
    return q,dict(gate=bool(valid.all()),sources=len(q),outsideOrBoundary=int(sum(~valid)),
        minimumChartMargin=float(d.min()),oldHalfspaceRejected=int(sum(~old)),
        falseHalfspaceRejections=int(sum(valid&~old)))
